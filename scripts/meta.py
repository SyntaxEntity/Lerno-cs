def get(subject_key):
    return TOPICS[subject_key]


def freq_line(subject_key, topic_name):
    """返回某知识点的标准考频统计行（供生成脚本与校验脚本共用）。"""
    for t in TOPICS[subject_key]:
        if t[0] == topic_name:
            name, times, years, ratio, qtype, hot, slug = t
            if times == PENDING:
                times_txt = PENDING
            else:
                times_txt = "%d 次" % times
            return "**考频统计**：考察次数 %s；涉及年份：%s；分数占比约 %s；主要题型：%s。" % (
                times_txt, years, ratio.replace("约 ", ""), qtype)
    raise KeyError((subject_key, topic_name))


